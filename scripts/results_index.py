"""Index every file in ``results/`` by the script and commit that produced it.

    uv run python scripts/results_index.py

Same split as ``RUNS.toml`` and ``MANIFEST.md``: the machine-recoverable part is
generated and committed, so the diff is the record of what changed, and the part
that cannot be recovered — *why* a measurement was taken — stays hand-written in
``results/README.md``.

The table was previously hand-maintained and fell 35 files behind, because
nothing in a results file said which script wrote it: the header printed
``sys.argv[1:]`` and dropped ``argv[0]``. ``goalmisgen/provenance.py`` fixes that
going forward, so every file written from now on names its own producer.

For the files already on disk the producer is inferred where it can be, by
matching the flags in the recorded ``argv`` against each script's argument
parser. That resolves fewer than half of them — many analysis scripts share
``--base``, ``--arms`` and ``--levels``, so the flags do not identify the script
— and inferred entries are marked with ``?`` rather than asserted. The remainder
are listed as unknown, which is the truthful answer and becomes rarer every time
a measurement is rerun.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from goalmisgen.provenance import parse_header  # noqa: E402

FLAG = re.compile(r"(?<!\S)--[a-z0-9-]+")


def parser_flags(script: Path) -> set[str]:
    """Every ``--flag`` the script's argument parser declares."""
    found: set[str] = set()
    for node in ast.walk(ast.parse(script.read_text())):
        if isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "add_argument":
            found |= {
                a.value
                for a in node.args
                if isinstance(a, ast.Constant) and isinstance(a.value, str) and a.value.startswith("--")
            }
    return found


def infer_script(argv: str, scripts: dict[str, set[str]]) -> str | None:
    """The one script whose parser accepts every flag used, if there is exactly one."""
    used = set(FLAG.findall(argv))
    if not used:
        return None
    candidates = [name for name, flags in scripts.items() if used <= flags]
    return candidates[0] if len(candidates) == 1 else None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--experiments", type=Path, default=Path("experiments"))
    parser.add_argument("--out", type=Path, default=Path("results/INDEX.md"))
    parser.add_argument("--generated-at", type=str, default=None)
    args = parser.parse_args()

    stamp = args.generated_at or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    scripts = {p.name: parser_flags(p) for p in sorted(args.experiments.glob("*.py"))}

    rows, recorded, inferred, unknown = [], 0, 0, 0
    for path in sorted(args.results.glob("*.txt")):
        found = parse_header(path.read_text())
        if found.script:
            producer, recorded = f"`{found.script}`", recorded + 1
        elif found.argv and (guess := infer_script(found.argv, scripts)):
            producer, inferred = f"`{guess}` ?", inferred + 1
        else:
            producer, unknown = "**unknown**", unknown + 1
        arguments = found.argv or ""
        if len(arguments) > 90:
            arguments = arguments[:87] + "..."
        rows.append((path.name, producer, found.commit or "—", f"`{arguments}`" if arguments else "—"))

    lines = [
        "# What produced each results file",
        "",
        f"Generated by `scripts/results_index.py` at {stamp}. Regenerate after any",
        "measurement; the diff is the record of what changed.",
        "",
        "`script` is read from the file's own header where it is there, and marked `?`",
        "where it was inferred from the flags in `argv` instead. **unknown** means the",
        "file predates the header, or its flags do not identify one script. Why each",
        "measurement was taken is in `README.md`, which is not generated.",
        "",
        "| file | script | commit | arguments |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{name}` | {producer} | `{commit}` | {arguments} |" for name, producer, commit, arguments in rows]
    lines += [
        "",
        f"{len(rows)} files: {recorded} name their own producer, {inferred} inferred from their flags,",
        f"{unknown} unknown.",
        "",
    ]
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}  ({len(rows)} files, {recorded} recorded, {inferred} inferred, {unknown} unknown)")


if __name__ == "__main__":
    main()
